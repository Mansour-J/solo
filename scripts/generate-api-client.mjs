#!/usr/bin/env node
// Regenerates the typed API client from the Rust API's OpenAPI document:
//   1. `solo-api openapi` → packages/api-client/openapi.json
//   2. openapi-typescript → packages/api-client/src/schema.d.ts
// CI runs this and fails if the committed files differ (the client must match the API).
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = fileURLToPath(new URL('..', import.meta.url));
const pkg = join(root, 'packages/api-client');
const cargo = process.platform === 'win32' ? 'cargo.exe' : 'cargo';

const spec = execFileSync(cargo, ['run', '--quiet', '--manifest-path', join(root, 'services/api/Cargo.toml'), '--', 'openapi'], {
  cwd: root,
  encoding: 'utf8',
  // Cargo is often only on PATH in login shells.
  env: { ...process.env, PATH: `${join(homedir(), '.cargo', 'bin')}:${process.env.PATH ?? ''}` },
  maxBuffer: 32 * 1024 * 1024,
});
const document = JSON.parse(spec);
writeFileSync(join(pkg, 'openapi.json'), `${JSON.stringify(document, null, 2)}\n`);

const ast = await openapiTS(document, { alphabetize: true });
const header = "// Generated by scripts/generate-api-client.mjs from the API's OpenAPI document. Do not edit.\n\n";
writeFileSync(join(pkg, 'src/schema.d.ts'), header + astToString(ast));
console.log(
  `API client generated: ${Object.keys(document.paths).length} paths, ${Object.keys(document.components?.schemas ?? {}).length} schemas`,
);
