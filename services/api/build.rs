//! Embeds the Flyway migrations (`database/migrations/V<n>__<description>.sql`) into the binary, so
//! the API can bring its own database up to date (`solo_api::migrations`), e.g. in the desktop app's
//! local mode where there is no Flyway.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

fn main() {
    let dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("manifest dir"))
        .join("../../database/migrations");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut migrations: Vec<(i32, String, PathBuf)> = fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", dir.display()))
        .filter_map(Result::ok)
        .filter_map(|entry| {
            let name = entry.file_name().to_string_lossy().into_owned();
            let rest = name.strip_prefix('V')?.strip_suffix(".sql")?;
            let (version, _) = rest.split_once("__")?;
            Some((
                version
                    .parse()
                    .unwrap_or_else(|_| panic!("bad migration name {name}")),
                name,
                entry.path(),
            ))
        })
        .collect();
    migrations.sort_by_key(|m| m.0);
    for pair in migrations.windows(2) {
        assert!(
            pair[0].0 != pair[1].0,
            "two migrations share version {}",
            pair[0].0
        );
    }
    let mut out = String::from(
        "/// Every migration, in version order (generated by build.rs).\npub static MIGRATIONS: &[Migration] = &[\n",
    );
    for (version, script, path) in &migrations {
        let description = script
            .trim_end_matches(".sql")
            .split_once("__")
            .map(|(_, d)| d.replace('_', " "))
            .unwrap_or_default();
        let path = fs::canonicalize(path).expect("canonical path");
        writeln!(
            out,
            "    Migration {{ version: {version}, description: {description:?}, script: {script:?}, sql: include_str!({path:?}) }},",
            path = path.display().to_string()
        )
        .expect("write");
    }
    out.push_str("];\n");
    fs::write(
        PathBuf::from(env::var("OUT_DIR").expect("out dir")).join("migrations.rs"),
        out,
    )
    .expect("write migrations.rs");
}
